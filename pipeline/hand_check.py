"""H1: the hand check (M1). Does the engine agree with a calculation done by hand?

Site (0, 0), smooth Moon, 2 m mast. Two independent routes to the next sunset and the sunlit share:
  HAND    the formula-sheet route: the sub-solar point from SPICE, Sun height from F5
          sin(e) = sin(lat) sin(b) + cos(lat) cos(b) cos(lon - l), sunset when the height reaches
          -(horizon dip + Sun radius).
  ENGINE  the app's route: vectors, local frame, flat horizon (illumination.conditions).
Run:  python pipeline/hand_check.py   (writes docs/validation/hand_check.md)
"""
from pathlib import Path

import numpy as np
import spiceypy as sp

from geometry import MOON_RADIUS_KM, SUN_RADIUS_KM, Site
from illumination import conditions, flat_mask

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_FILE = REPO_ROOT / "docs" / "validation" / "hand_check.md"
START_UTC = "2026-11-14T09:00:00"
LAT_DEG, LON_DEG, MAST_M = 0.0, 0.0, 2.0
SYNODIC_DAYS = 29.530589


def hand_height_and_threshold(ets: np.ndarray) -> tuple[np.ndarray, np.ndarray, float]:
    """Sun height by F5, and the height at which the disc has just fully set, for each time."""
    sun = np.array(sp.spkpos("SUN", ets, "MOON_ME", "CN+S", "MOON")[0])
    dist = np.linalg.norm(sun, axis=1)
    b = np.arcsin(sun[:, 2] / dist)                      # sub-solar latitude
    lon_sun = np.arctan2(sun[:, 1], sun[:, 0])           # sub-solar longitude
    lat, lon = np.radians(LAT_DEG), np.radians(LON_DEG)
    sin_e = np.sin(lat) * np.sin(b) + np.cos(lat) * np.cos(b) * np.cos(lon - lon_sun)   # F5
    height = np.degrees(np.arcsin(sin_e))
    radius = np.degrees(np.arcsin(SUN_RADIUS_KM / dist))                                # F15
    dip = float(np.degrees(np.arccos(MOON_RADIUS_KM / (MOON_RADIUS_KM + MAST_M / 1000.0))))
    return height, -(dip + radius), dip


def first_sunset(ets: np.ndarray, gap: np.ndarray) -> float:
    """TDB time of the first time gap goes from above zero to zero or below, refined by linear steps."""
    i = int(np.flatnonzero((gap[:-1] > 0) & (gap[1:] <= 0))[0])
    return float(ets[i] + (ets[i + 1] - ets[i]) * gap[i] / (gap[i] - gap[i + 1]))


def run_h1() -> dict:
    t0 = sp.str2et(START_UTC)
    ets = t0 + 60.0 * np.arange(round(SYNODIC_DAYS * 1440) + 1)          # one lunar day, 1-minute steps

    height, threshold, dip = hand_height_and_threshold(ets)
    hand_gap = height - threshold
    hand_sunset = first_sunset(ets, hand_gap)
    hand_lit = 100.0 * float(np.mean(hand_gap > 0))

    site = Site(LAT_DEG, LON_DEG, 0.0, MAST_M)
    c = conditions(site, ets, flat_mask(site))
    engine_gap = c["sun_el"] + c["sun_radius"] + dip      # disc's top edge above the flat horizon (-dip)
    engine_sunset = first_sunset(ets, engine_gap)
    engine_lit = 100.0 * float(np.mean(c["terrain_fraction"] > 0))

    gap_min = abs(hand_sunset - engine_sunset) / 60.0
    gap_pts = abs(hand_lit - engine_lit)
    ok = gap_min <= 2.0 and gap_pts <= 0.5
    when = lambda t: sp.et2utc(t, "ISOC", 0) + " UTC"  # noqa: E731
    print(f"  H1 hand check: sunset {when(hand_sunset)} (hand) vs {when(engine_sunset)} (engine), "
          f"{gap_min:.2f} min apart; sunlit {hand_lit:.2f}% vs {engine_lit:.2f}%")

    write_report(hand_sunset, engine_sunset, gap_min, hand_lit, engine_lit, dip, ok)
    return {
        "id": "H1",
        "name": "Hand check: first sunset and sunlit share at (0, 0)",
        "what": ("At (0, 0) on a smooth Moon with a 2 m mast, the next sunset and the sunlit share of one lunar day, "
                 "found two ways: by hand from formula F5 and by the app's engine."),
        "tolerance": "sunset within 2 minutes; sunlit share within 0.5 points",
        "result": round(gap_min, 2),
        "unit": "minutes (sunset, hand vs engine)",
        "expected_outcome": "pass",
        "outcome": "pass" if ok else "fail",
        "explanation": (f"Hand: {when(hand_sunset)}, engine: {when(engine_sunset)}. Sunlit share {hand_lit:.2f}% by hand, "
                        f"{engine_lit:.2f}% by the engine ({gap_pts:.2f} points apart). Worked steps are in "
                        "docs/validation/hand_check.md."),
        "details": {"hand_sunset_utc": when(hand_sunset), "engine_sunset_utc": when(engine_sunset),
                    "hand_lit_percent": round(hand_lit, 3), "engine_lit_percent": round(engine_lit, 3)},
    }


def write_report(hand_sunset, engine_sunset, gap_min, hand_lit, engine_lit, dip, ok) -> None:
    when = lambda t: sp.et2utc(t, "ISOC", 0) + " UTC"  # noqa: E731
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(f"""# Hand check (H1)

Generated by `pipeline/hand_check.py`. Site (0 N, 0 E), smooth Moon, {MAST_M:g} m mast. Start {START_UTC} UTC.

## By hand (formula F5)

1. Ask SPICE where the Sun is from the Moon's centre (frame MOON_ME, light-time CN+S).
2. The point of the Moon directly under the Sun has latitude b and longitude l.
3. The Sun's height at the site: sin(e) = sin(lat) sin(b) + cos(lat) cos(b) cos(lon - l).
4. The Sun has fully set when its whole disc is under the horizon: height = -(dip + Sun radius).
   - dip = acos(R / (R + h)) = {dip:.4f} degrees for a {MAST_M:g} m mast
   - Sun radius = asin(695,700 km / distance), about 0.267 degrees (F15)
5. First time that happens: **{when(hand_sunset)}**.

## By the engine

The app's route: Sun vector minus site vector, rotated into the site's east-north-up frame, compared with a flat horizon.
First sunset: **{when(engine_sunset)}**.

## Result

| | By hand | Engine |
|---|---|---|
| First sunset | {when(hand_sunset)} | {when(engine_sunset)} |
| Sunlit share of one lunar day (29.53 d) | {hand_lit:.2f}% | {engine_lit:.2f}% |

Sunset differs by {gap_min:.2f} minutes (limit 2). Sunlit share differs by {abs(hand_lit - engine_lit):.2f} points (limit 0.5).
Result: **{"pass" if ok else "FAIL"}**.

The engine also subtracts the site's position from the Sun's (F3), which the hand route leaves out. For the Sun that changes the direction by under 0.0007 degrees, which is why the two agree.
""", encoding="utf-8")


if __name__ == "__main__":
    from spice_setup import load_kernels

    load_kernels()
    print(run_h1()["explanation"])
