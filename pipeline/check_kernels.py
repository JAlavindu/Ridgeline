import difflib
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import spiceypy as sp

from spice_setup import KERNEL_DIR, KERNEL_FILES, load_kernels

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = REPO_ROOT / "docs"
REPORT = DOCS_DIR / "kernel_checks.txt"
FRAME_DIFF = DOCS_DIR / "frame_kernel_diff.txt"

results = []


def check(name: str, passed: bool, detail: str) -> None:
    """Print one check result and remember it for the report."""
    status = "PASS" if passed else "FAIL"
    line = f"[{status}] {name}: {detail}"
    print(line)
    results.append((passed, line))


def check_frames() -> None:
    for frame in ["MOON_ME", "MOON_PA"]:
        frame_id = sp.namfrm(frame)
        check(f"frame {frame} exists", frame_id != 0, f"frame ID {frame_id}")


def check_radii() -> None:
    radii = sp.bodvrd("MOON", "RADII", 3)[1]
    ok = np.allclose(radii, 1737.4)
    check("Moon radii", ok, f"{radii} km (expected 1737.4 x3)")


def check_pa_me_angle() -> None:
    et = sp.str2et("2026-11-14T12:00:00")
    rotation = sp.pxform("MOON_PA", "MOON_ME", et)
    angle_deg = np.degrees(np.arccos((np.trace(rotation) - 1) / 2))
    metres = np.radians(angle_deg) * 1737.4e3
    ok = abs(angle_deg - 0.0289) < 0.001
    check("MOON_PA vs MOON_ME angle", ok,
          f"{angle_deg:.5f} deg = {metres:.0f} m on the surface (expected ~0.0289 deg, ~875 m)")


def check_time_round_trip() -> None:
    utc_in = "2026-11-14T09:00:00.000"
    et = sp.str2et(utc_in)
    utc_out = sp.et2utc(et, "ISOC", 3)
    check("UTC -> TDB -> UTC round trip", utc_out == utc_in, f"{utc_in} -> {et:.4f} s -> {utc_out}")

    browser_formula = 847_918_869.184
    gap = abs(et - browser_formula)
    check("TDB anchor (2026-11-14 09:00 UTC)", gap < 0.002,
          f"SPICE {et:.4f} s vs browser formula {browser_formula} s, gap {gap:.4f} s (limit 0.002)")


def sub_solar_latitudes() -> tuple[np.ndarray, np.ndarray]:
    """Latitude of the point where the Sun is overhead, every 6 hours, 2023-2032."""
    start = sp.str2et("2023-01-01T00:00:00")
    end = sp.str2et("2033-01-01T00:00:00")
    ets = np.arange(start, end, 6 * 3600.0)
    positions, _ = sp.spkpos("SUN", ets, "MOON_ME", "CN+S", "MOON")
    positions = np.array(positions)
    distances = np.linalg.norm(positions, axis=1)
    latitudes = np.degrees(np.arcsin(positions[:, 2] / distances))
    return ets, latitudes


def check_sun_latitude_and_season() -> None:
    ets, lat = sub_solar_latitudes()

    # The plan says ~1.54 deg, but that is only the mean tilt of the lunar equator (1.543).
    # Physical libration and the Moon's offset from the ecliptic add ~0.045 deg:
    # measured 1.588 deg (2029-09-23), confirmed with IAU_MOON (1.587). Reported to M1.
    max_lat = np.abs(lat).max()
    check("max sub-solar latitude 2023-2032", 1.54 <= max_lat <= 1.60,
          f"{max_lat:.4f} deg (expected 1.54-1.60: 1.543 mean tilt + libration)")

    crossings = ets[1:][(lat[:-1] < 0) & (lat[1:] >= 0)]
    keep = np.insert(np.diff(crossings) > 100 * 86400, 0, True)
    crossings = crossings[keep]
    season_days = np.diff(crossings).mean() / 86400
    check("mean lunar season", abs(season_days - 346.6) < 1.0,
          f"{season_days:.2f} days from {len(crossings)} northward equator crossings (expected ~346.6)")


def check_azlcpo() -> None:
    toolkit = sp.tkvrsn("TOOLKIT")
    ok = hasattr(sp, "azlcpo") and toolkit == "CSPICE_N0067"
    check("azlcpo available", ok, f"SpiceyPy {sp.__version__}, {toolkit}")


def write_frame_kernel_diff() -> None:
    """Save the differences between the old and new Moon frame kernels for a human to read."""
    old = (KERNEL_DIR / "moon_de440_220930.tf").read_text().splitlines()
    new = (KERNEL_DIR / "moon_de440_250416.tf").read_text().splitlines()
    diff = list(difflib.unified_diff(old, new, "moon_de440_220930.tf", "moon_de440_250416.tf", lineterm=""))
    FRAME_DIFF.write_text("\n".join(diff) + "\n")
    changed = sum(1 for line in diff if line[:1] in "+-" and line[:3] not in ("+++", "---"))
    check("frame kernel diff written", True,
          f"{changed} changed lines -> {FRAME_DIFF.relative_to(REPO_ROOT).as_posix()} (read it and note what changed)")


def main() -> None:
    DOCS_DIR.mkdir(exist_ok=True)
    load_kernels()

    check_frames()
    check_radii()
    check_pa_me_angle()
    check_time_round_trip()
    check_sun_latitude_and_season()
    check_azlcpo()
    write_frame_kernel_diff()

    failures = sum(1 for passed, _ in results if not passed)
    summary = f"{len(results) - failures}/{len(results)} checks passed"
    print(summary)

    header = [
        "Ridgeline kernel checks (generated by pipeline/check_kernels.py)",
        f"Run at: {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC",
        "Kernels: " + ", ".join(KERNEL_FILES),
        "",
    ]
    REPORT.write_text("\n".join(header + [line for _, line in results] + ["", summary]) + "\n")
    print("Report saved to", REPORT.relative_to(REPO_ROOT).as_posix())

    if failures:
        sys.exit(1)


if __name__ == "__main__":
    main()
