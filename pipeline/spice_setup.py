from pathlib import Path

import spiceypy as sp

KERNEL_DIR = Path(__file__).resolve().parent / "kernels"
META_KERNEL = KERNEL_DIR / "ridgeline.tm"
KERNEL_FILES = [
    "naif0012.tls",               # leap seconds (UTC <-> TDB)
    "pck00011.tpc",               # body sizes (Moon radius 1737.4 km)
    "de440s.bsp",                 # Sun, Earth, Moon positions
    "moon_pa_de440_200625.bpc",   # Moon orientation, incl. libration
    "moon_de440_250416.tf",       # Moon frames, incl. MOON_ME
]
# Only for DSN mode (module 12); loaded on top of the main set by load_dsn_kernels()
DSN_KERNEL_FILES = [
    "earthstns_itrf93_260814.bsp",
    "earth_topo_260814.tf",
    "earth_1962_260806_2126_combined.bpc",
]
MAX_PIECE = 78


def spice_string_lines(text: str) -> list[str]:
    """Quote a string for a SPICE text kernel, splitting it if it is too long."""
    pieces = [text[i:i + MAX_PIECE] for i in range(0, len(text), MAX_PIECE)]
    quoted = [f"'{piece}+'" for piece in pieces[:-1]]
    quoted.append(f"'{pieces[-1]}'")
    return quoted


def write_meta_kernel() -> Path:
    """Write ridgeline.tm listing every kernel by absolute path. Returns its path."""
    missing = [name for name in KERNEL_FILES if not (KERNEL_DIR / name).exists()]
    if missing:
        raise FileNotFoundError(
            f"Missing kernels {missing} in {KERNEL_DIR}. "
            "Run: python pipeline/get_kernels.py"
        )

    kernel_dir = KERNEL_DIR.as_posix()  # forward slashes, which SPICE accepts on Windows

    lines = ["KPL/MK", "", "Generated by pipeline/spice_setup.py. Do not edit.", ""]
    lines.append("\\begindata")
    lines.append("")
    lines.append("PATH_VALUES = (")
    lines += ["    " + s for s in spice_string_lines(kernel_dir)]
    lines.append("    )")
    lines.append("PATH_SYMBOLS = ( 'KERNELS' )")
    lines.append("")
    lines.append("KERNELS_TO_LOAD = (")
    lines += [f"    '$KERNELS/{name}'" for name in KERNEL_FILES]
    lines.append("    )")
    lines.append("")
    lines.append("\\begintext")
    lines.append("")

    META_KERNEL.write_text("\n".join(lines))
    return META_KERNEL


def load_kernels() -> None:
    """Clear SPICE, then load all Ridgeline kernels through the meta-kernel."""
    meta_kernel = write_meta_kernel()
    sp.kclear()
    sp.furnsh(str(meta_kernel))


def load_dsn_kernels() -> None:
    """The main kernels plus the Earth-station kernels. Run get_kernels.py --dsn first."""
    load_kernels()
    for name in DSN_KERNEL_FILES:
        path = KERNEL_DIR / name
        if not path.exists():
            raise FileNotFoundError(f"Missing {name}. Run: python pipeline/get_kernels.py --dsn")
        sp.furnsh(str(path))


if __name__ == "__main__":
    load_kernels()
    print("Meta-kernel:", META_KERNEL)
    print("Kernels loaded:", sp.ktotal("ALL"))
    print("Moon radii (km):", sp.bodvrd("MOON", "RADII", 3)[1])
